export function mergeRuKeywordsIntoEmojiData<T extends { emojis: Record<string, { keywords?: string[] }> }>(
  data: T,
): T {
  for (const [id, ruWords] of Object.entries(EMOJI_RU_KEYWORDS)) {
    const emoji = data.emojis[id];
    if (!emoji) continue;
    const existing = emoji.keywords ?? [];
    emoji.keywords = [...existing, ...ruWords];
  }
  return data;
}
