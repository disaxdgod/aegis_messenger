const EMPLOYEE_BY_USERNAME = Object.fromEntries(
  DEMO_EMPLOYEES.map((e) => [e.username, e]),
) as Record<string, DemoEmployee>;

export function demoEmployeeDisplayName(e: DemoEmployee): string {
  return `${e.firstName} ${e.lastName}`;
}

export function demoAvatar(username: string): string {
  return `https://api.dicebear.com/9.x/notionists-neutral/svg?seed=${encodeURIComponent(username)}&backgroundColor=f0f4f8,e8eef5,dce4ec`;
}

function postAuthor(username: string) {
  const e = EMPLOYEE_BY_USERNAME[username];
  return {
    name: demoEmployeeDisplayName(e),
    username: e.username,
    avatarUrl: demoAvatar(e.username),
  };
}

function pollVoter(username: string) {
  const e = EMPLOYEE_BY_USERNAME[username];
  return {
    voterId: e.username,
    name: demoEmployeeDisplayName(e),
    username: e.username,
    avatarUrl: demoAvatar(e.username),
  };
}

function commentAuthor(username: string) {
  return {
    authorName: demoEmployeeDisplayName(EMPLOYEE_BY_USERNAME[username]),
    authorAvatar: demoAvatar(username),
  };
}

